import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import { calibrate, SERVICE_TIMEOUT, SERVICE_URL, useLocalService } from './support';

/**
 * G3.1 Phase 8 — performance with the local vision service, measured in Chromium on this
 * machine: frame round trips (as the remote worker sees them on the network), frames per
 * second, payload sizes and the service's resident memory over a run. Writes
 * docs/testing/service-performance.md.
 */
const RUN_MS = 45_000;
const REPORT = 'docs/testing/service-performance.md';
const PORT = Number(new URL(SERVICE_URL).port);

/** Resident memory of the process listening on the service port, in MB (null if unknown). */
function serviceRssMb(): number | null {
  try {
    if (process.platform === 'win32') {
      const netstat = execSync('netstat -ano -p TCP', { encoding: 'utf8' });
      const line = netstat
        .split(/\r?\n/)
        .find((l) => l.includes(`127.0.0.1:${PORT}`) && l.includes('LISTENING'));
      const pid = line?.trim().split(/\s+/).at(-1);
      if (!pid) return null;
      const csv = execSync(`tasklist /FI "PID eq ${pid}" /FO CSV /NH`, { encoding: 'utf8' });
      const kb = Number(
        csv
          .split('","')
          .at(-1)
          ?.replace(/[^0-9]/g, ''),
      );
      return Number.isFinite(kb) ? kb / 1024 : null;
    }
    const pid = execSync(`lsof -ti tcp:${PORT} -sTCP:LISTEN`, { encoding: 'utf8' }).trim();
    const status = readFileSync(`/proc/${pid}/status`, 'utf8');
    const kb = Number(/VmRSS:\s+(\d+)/.exec(status)?.[1]);
    return Number.isFinite(kb) ? kb / 1024 : null;
  } catch {
    return null;
  }
}

const quantile = (values: number[], q: number): number => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.round(q * (sorted.length - 1)))] ?? 0;
};

test('profiles recognition through the local service', async ({ page }) => {
  test.setTimeout(RUN_MS + 120_000);
  await useLocalService(page);
  await calibrate(page);
  await expect(page.getByTestId('recognition-status')).toHaveText('Leitura confiável', {
    timeout: SERVICE_TIMEOUT,
  });

  const roundTrips: number[] = [];
  const payloads: number[] = [];
  const sizes: Promise<unknown>[] = [];
  const serviceMs: number[] = [];
  const failures: string[] = [];
  page.context().on('requestfinished', (request) => {
    if (!request.url().includes('/frames')) return;
    const timing = request.timing();
    roundTrips.push(timing.responseEnd);
    // Bodies posted by a worker are not exposed to Playwright: the service reports them.
    sizes.push(
      request
        .response()
        .then((response) => response?.json())
        .then((body: { timings?: { requestBytes?: number; totalMs?: number } }) => {
          if (body?.timings?.requestBytes) payloads.push(body.timings.requestBytes);
          if (body?.timings?.totalMs) serviceMs.push(body.timings.totalMs);
        }),
    );
  });
  page.context().on('requestfailed', (request) => {
    if (request.url().includes('/frames')) failures.push(request.failure()?.errorText ?? '?');
  });

  const rssStart = serviceRssMb();
  const started = Date.now();
  await page.waitForTimeout(RUN_MS);
  const elapsed = (Date.now() - started) / 1000;
  const rssEnd = serviceRssMb();
  await expect(page.getByTestId('recognition-status')).toHaveText('Leitura confiável');

  await Promise.allSettled(sizes);
  expect(roundTrips.length).toBeGreaterThan(50);
  expect(failures).toEqual([]);
  const fps = roundTrips.length / elapsed;
  const mb = (value: number | null) => (value === null ? 'not measured' : `${value.toFixed(1)} MB`);
  const lines = [
    '# Performance — local vision service (G3.1)',
    '',
    '<!-- Generated by `npm run e2e:service` (tests/e2e-service/profile.service.spec.ts). Do not edit by hand. -->',
    '',
    `Measured ${new Date().toISOString().slice(0, 10)} on this machine, Chromium with the synthetic board camera ` +
      '(640 × 480 frames), the app on the dev server and the service on 127.0.0.1. Targets from the G3.1 design §9.',
    '',
    '| Measure | Result | Target |',
    '| --- | ---: | ---: |',
    `| Frames recognized | ${roundTrips.length} in ${elapsed.toFixed(0)} s (${fps.toFixed(1)} /s) | 5 /s (200 ms interval) |`,
    `| Round trip per frame (request start → response end), median | ${quantile(roundTrips, 0.5).toFixed(0)} ms | — |`,
    `| Round trip p90 | ${quantile(roundTrips, 0.9).toFixed(0)} ms | ≤ 150 ms |`,
    `| Round trip max | ${Math.max(...roundTrips).toFixed(0)} ms | — |`,
    `| Service processing per frame (decode + warp + recognition), median / p90 | ${quantile(serviceMs, 0.5).toFixed(0)} / ${quantile(serviceMs, 0.9).toFixed(0)} ms | ≤ 50 / ≤ 80 ms |`,
    `| JPEG payload per frame, median | ${(quantile(payloads, 0.5) / 1024).toFixed(0)} kB | ≤ 400 kB |`,
    `| Failed frame requests | ${failures.length} | 0 |`,
    `| Service resident memory, start → end of the run | ${mb(rssStart)} → ${mb(rssEnd)} | flat (±10 %) |`,
    '',
    'The round trip excludes the JPEG encoding in the remote worker (before the request) and the bitmap ' +
      'decoding after it. Service-side processing per real 1280 × 720 frame is in ' +
      '`docs/vision/service-metrics.md`. One frame is in flight at a time; the frame scheduler drops stale frames.',
    '',
  ];
  writeFileSync(REPORT, lines.join('\n'));
});
