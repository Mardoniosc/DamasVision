import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from '@playwright/test';
import { calibrateAndRecognize, heapAfterGc, startGameFromRecognition } from '../e2e/support/flows';

/**
 * E8-T03 — profiling on the production build, in Chromium with the synthetic board
 * camera. Writes docs/testing/performance.md with the measured values (machine-dependent:
 * the report records where they were taken).
 */
const DIST = join(process.cwd(), 'dist', 'damas-vision', 'browser');
const MB = 1024 * 1024;

function bundleSizes() {
  const files = readdirSync(DIST).filter((name) => /\.(js|css)$/.test(name));
  const size = (name: string) => statSync(join(DIST, name)).size;
  const initial = files.filter((name) => /^(main|styles|polyfills)-/.test(name));
  const opencv = files
    .filter((name) => name.startsWith('worker-chunk'))
    .sort((a, b) => size(b) - size(a))[0];
  const total = files.reduce((sum, name) => sum + size(name), 0);
  return {
    initialKb: Math.round(initial.reduce((sum, name) => sum + size(name), 0) / 1024),
    opencvMb: opencv ? size(opencv) / MB : 0,
    totalMb: total / MB,
  };
}

test('profile the production build', async ({ page }) => {
  test.setTimeout(240_000);
  const bundles = bundleSizes();

  // First load (no service worker yet).
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1, name: 'Damas Vision' })).toBeVisible();
  const navigation = await page.evaluate(() => {
    const entry = performance.getEntriesByType('navigation')[0] as PerformanceNavigationTiming;
    const paint = performance.getEntriesByName('first-contentful-paint')[0];
    return {
      domContentLoaded: entry.domContentLoadedEventEnd,
      load: entry.loadEventEnd,
      fcp: paint?.startTime ?? null,
    };
  });

  // Time to a reliable reading: route → camera → worker + OpenCV.js → stabilized board.
  await page.goto('/calibration');
  await expect(page.getByTestId('calibration-validity')).toHaveText('Calibração válida');
  await page.getByRole('button', { name: 'Salvar calibração' }).click();
  const started = Date.now();
  await page.getByRole('link', { name: 'Continuar para o reconhecimento' }).click();
  await expect(page.getByTestId('recognition-status')).toHaveText('Leitura confiável', {
    timeout: 60_000,
  });
  const firstReadingMs = Date.now() - started;

  // Analysis throughput over 10 s (target: one frame every 200 ms).
  const frames = async () =>
    Number((await page.getByTestId('frames-processed').textContent()) ?? 0);
  const before = await frames();
  await page.waitForTimeout(10_000);
  const framesPerSecond = ((await frames()) - before) / 10;

  // A live game: heap over 30 s.
  await calibrateAndRecognize(page);
  await startGameFromRecognition(page);
  const heapStart = await heapAfterGc(page);
  await page.waitForTimeout(30_000);
  const heapEnd = await heapAfterGc(page);

  const report = [
    '# Performance (E8-T03)',
    '',
    '<!-- Generated by `npm run e2e:prod` (tests/e2e-prod/profile.spec.ts). Do not edit by hand. -->',
    '',
    `Measured ${new Date().toISOString().slice(0, 10)} on the production build, in Playwright Chromium (desktop), with the synthetic board camera (640 × 480). Values depend on the machine; they are a baseline, not a guarantee.`,
    '',
    '| Measure | Value | Target / note |',
    '| --- | ---: | --- |',
    `| Initial bundle (main + styles) | ${bundles.initialKb} kB | budget 500 kB warning / 1 MB error |`,
    `| OpenCV.js worker chunk | ${bundles.opencvMb.toFixed(1)} MB | loaded only by the vision worker; cached by the service worker |`,
    `| All JS + CSS | ${bundles.totalMb.toFixed(1)} MB | |`,
    `| First contentful paint (home) | ${navigation.fcp === null ? 'not reported' : `${Math.round(navigation.fcp)} ms`} | headless Chromium may not report paint timing |`,
    `| DOMContentLoaded / load (home) | ${Math.round(navigation.domContentLoaded)} / ${Math.round(navigation.load)} ms | |`,
    `| Recognition page → first reliable reading | ${(firstReadingMs / 1000).toFixed(1)} s | includes camera start, worker and OpenCV.js load, ≥ 3 agreeing frames |`,
    `| Frames analysed per second | ${framesPerSecond.toFixed(1)} | 5 (one every 200 ms); lower means the worker is the bottleneck |`,
    `| Main-thread heap, live game, after GC | ${(heapStart / MB).toFixed(1)} → ${(heapEnd / MB).toFixed(1)} MB over 30 s | no growth expected (E8-T04) |`,
    '',
    'Per-frame processing in the worker, measured in Node on the real samples (docs/vision/recognition.md): `PROCESS_FRAME` median 46 ms (p90 50 ms). Move confirmation after the board settles: median 0.8 s (docs/vision/move-inference.md).',
    '',
  ].join('\n');
  writeFileSync(join(process.cwd(), 'docs', 'testing', 'performance.md'), report);

  expect(bundles.initialKb).toBeLessThan(1024);
  expect(framesPerSecond).toBeGreaterThan(3.5);
  expect(firstReadingMs).toBeLessThan(20_000);
  expect(heapEnd - heapStart).toBeLessThan(8 * MB);
});
